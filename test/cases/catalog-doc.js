// 生成 docs/业务测试用例.md：角色与用例对照、工作流阶段、起始状态、每个用例的步骤与预期。
// 角色、阶段、起始状态的说明文字是人工维护的（业务视角），用例编号与步骤数由 test/cases/ 下的定义实时算出。
const fw = require("./framework.js");
const { CASES: DECISION } = require("./decision-cases.js"), { CASES: QA } = require("./qa-cases.js");
const { CHAIN } = fw;

const ROLE_DESC = [
  ["优化本体", "自动建单、规则定因、生成方案、写入效果（SPEC 只授权这四类）"],
  ["地市优化工程师", "核验确认或排除、审批并派单、裁定工参冲突、提问"],
  ["优化主管", "追加批准多小区变更、关闭工单"],
  ["现场维护人员", "按派单调整并回填实际值"],
  ["优化专家", "复核改因、案例入库"],
  ["知识维护人", "案例入库"],
  ["MR 平台", "每天凌晨推送 MR 日统计，也可能事后更正"],
  ["资源系统", "工参与目标覆盖半径的来源，可能在方案生成后变化"],
  ["网管", "小区名称等基础数据维护"],
  ["系统", "只读核对（约束、审计、矩阵）"]
];
const STAGES = [
  ["发现与建单", "看发现清单，对达到的小区建单；数据没到齐、数据更正怎么办", "BD-01、BD-02、BD-25、BD-29", "BQ-01、BQ-09"],
  ["核验与定因", "看依据和告警，次因并列、假性弱覆盖、工参缺失、专家改因，5G／室分转人工", "BD-03～BD-09、BD-28", "BQ-02、BQ-03"],
  ["方案与审批", "机械还是电子，同天线小区受限，多小区追加主管批准，方案过期，关系变化", "BD-10～BD-12、BD-26", "BQ-04、BQ-05"],
  ["现场执行", "回填实际值、重复提交、偏差复核、回执缺失、工参冲突与裁定", "BD-13～BD-16", "BQ-06"],
  ["效果与关单", "第 1／2 周评估，持续有效、未达标、劣化、后窗不足，关单", "BD-17～BD-22", "BQ-07"],
  ["入库与复用", "案例入库与复用，关单后复发", "BD-17、BD-23", "BQ-08、BQ-14"],
  ["规则与边界", "权限矩阵、规则咨询、范围外请求、与真实工单对账、主管全局、改名不改历史", "BD-24、BD-27", "BQ-10～BQ-13"]
];

const whoOf = s => (s.k === "act" ? s.actor.role : s.role);
const casesOf = role => [...DECISION, ...QA].filter(c => c.steps.some(s => whoOf(s) === role)).map(c => c.id);

function catalogDoc() {
  let md = `# 业务测试用例（决策与问答）\n\n`;
  md += "本文是 `本体应用_上海工单` 的业务测试用例清单，由 `test/cases/` 下的用例定义自动生成。用例**按业务人员的实际使用顺序编排**：谁、在什么状态下、做什么或问什么、预期看到什么；全部在上海种子数据（`data/seed/*.csv`）上执行，MR 日统计随到达时间入库，不预置任何结论。\n\n";
  md += "与 SPEC 一致性测试（DS01～DS09、问答评测，见 `测试说明.md`）的分工：那一层回答“SPEC 定义的东西是否都实现并被用到”，按 SPEC 用例（TC）组织；这一层回答“业务人员这样用，系统是否表现正确、回答是否靠谱”，按角色和工作流组织。两层共用同一套代码与数据，互不替代。\n\n";
  md += `## 一、角色与用例\n\n| 角色 | 在系统里做什么 | 参与的用例 |\n|---|---|---|\n` +
    ROLE_DESC.map(([r, d]) => `| ${r} | ${d} | ${casesOf(r).join("、")} |`).join("\n") + "\n\n";
  md += `## 二、业务工作流与用例对照\n\n| 阶段 | 业务上做什么 | 决策用例 | 问答用例 |\n|---|---|---|---|\n` +
    STAGES.map(s => `| ${s[0]} | ${s[1]} | ${s[2]} | ${s[3]} |`).join("\n") + "\n\n";
  md += `## 三、起始状态\n\n每个用例从下面某个业务状态开始（状态是前一个状态再往前走一步，由优化本体和各角色通过正式动作入口走到，不是直接写库）。未列出的数据变化（例如“资源系统补录挂高”）在用例步骤里明写。\n\n| 状态 | 说明 | 用例 |\n|---|---|---|\n` +
    CHAIN.map(([w]) => `| ${w} | ${fw.WORLDS[w]} | ${[...DECISION, ...QA].filter(c => c.world === w).map(c => c.id).join("、")} |`).join("\n") + "\n\n";
  md += `## 四、步骤与预期的写法\n\n- **动作步骤**：某个角色通过动作入口（A_01～A_11）执行；预期要么“成功＋若干核对”，要么“被某条约束／权限／状态检查拒绝”（给出拒绝码）。拒绝也要留审计，且不产生业务记录。\n- **提问步骤**：带提问者角色的口语化提问；核对意图、回答里必须出现的事实、不得出现的内容、数值与日期落地检查（每个数字都必须能在本次引用的函数结果、对象或 SPEC 规则里找到）、是否写库（只有优化本体被授权的动作可以由提问触发，且写入 1 条审计）、需要人工执行的动作是否被提示。\n- **时间与外部数据**：推进时钟后，到达时间已到的 MR 日统计自动入库；MR 平台更正、资源系统变更等外部事件用明写的步骤表示。\n- 回答不使用大模型，由规则按本体元数据与函数结果生成；SPEC 没有定义的内容（置信度、预测、下倾以外的措施、NR 公式）如实回答“没有定义”。\n\n`;
  md += fw.catalog(DECISION, "五、决策用例（BD）", "决策用例覆盖业务上的正常路径、异常与拒绝路径。每个用例的“预期”列同时是断言说明。", 2) + "\n\n";
  md += fw.catalog(QA, "六、问答案例（BQ）", "\n问答用例是一段段多轮对话，中间穿插该角色的系统操作。提问都是业务人员平时的说法，不是接口式的关键词。", 2);
  return md;
}
module.exports = { catalogDoc };
